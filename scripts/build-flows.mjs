#!/usr/bin/env node
// Builds the GitHub flows in flows/ from the blocks in blocks/, so they never drift apart.
// Usage: node scripts/build-flows.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse, stringify } from "yaml";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const block = (id) => parse(readFileSync(join(root, "blocks", `${id}.yaml`), "utf8")).steps;
const steps = (...ids) => ids.flatMap((id) => (typeof id === "string" ? block(id) : [id]));
const patch = (list, id, fields) => Object.assign(list.find((s) => s.id === id), fields);
// issue-deliver/gitflow replace this sentence in the implement prompt — keep one copy.
const FOLLOW_PLAN = "Follow the plan in the latest \"Spaghetti Code Foundry plan\" comment (older ones are headed\n\"claude-factory plan\"), including any later comments from people, which override it. The bold first\nline of that comment is for the owner, not a step of the plan.";
// The closing sentence of the result comment: issue-deliver swaps the first for the second, issue-gitflow the second for its own.
const SHIPS_DAILY = "_This goes to main with the release pull request._";
const SHIPS_DELIVER = "_It is in the release pull request: $FACTORY_OUT_OPEN_PR — merge it whenever you like._";
// Like String.replace, but a text that is gone is an error (a silent no-op would ship the old wording).
const swap = (text, from, to) => {
  if (!text.includes(from)) throw new Error(`build-flows: nothing to replace: ${from}`);
  return text.replace(from, () => to);
};

// The shipped flows are the two pipelines and what supports them:
//   human in the loop — issue-plan → (you add Factory_code) → issue-code-daily → daily-pr
//   gitflow           — epic-questions → issue-gitflow → release-daily
// Everything else is retired: still generated (the tests run on these flows), but not shipped.
const RETIRED = new Set(["chore", "ci-fix", "github-auto", "github-issue", "github-pr", "jira-ticket", "linear-ticket", "pr-feedback", "issue-deliver"]);

function write(name, header, flow) {
  const text = `# ${"─".repeat(3)} ${header.title} ${"─".repeat(Math.max(3, 66 - header.title.length))}
# Generated by scripts/build-flows.mjs from blocks/*.yaml — edit the blocks or the script.
${header.lines.map((l) => `# ${l}`).join("\n")}
# ${"─".repeat(72)}
`;
  // Flows that change code: one run per repository at a time. Planning / PR-only flows run in parallel.
  const { description, workspace, ...rest } = flow;
  const coding = !["issue-plan", "daily-pr", "epic-questions", "release-daily", "issue-gitflow"].includes(name);
  const ordered = { name, description, workspace, ...(coding ? { one_per_repo: true } : {}), ...rest };
  // Retired flows are no longer shipped; they stay as test material (tests/fixtures/flows).
  const dir = RETIRED.has(name) ? join("tests", "fixtures", "flows") : "flows";
  writeFileSync(join(root, dir, `${name}.yaml`), text + stringify(ordered, { lineWidth: 0 }));
  console.log(`wrote ${dir}/${name}.yaml (${flow.steps.length} steps)`);
}

const ticketStart = () => {
  const s = steps("github-repo", "pull-ticket", "pull-repo", "plan", "push-plan", "code", "run-tests", "code-review");
  // After someone answers the questions, re-read the ticket and plan again.
  patch(s, "ask_for_info", { resume_from: "pull_ticket" });
  // After review changes, re-run the tests before reviewing again.
  patch(s, "address_review", { on_success: "run_tests" });
  return s;
};

